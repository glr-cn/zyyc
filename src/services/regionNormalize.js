// 预处理：按长度降序，保证「最长匹配」优先（如「内蒙古自治区」先于「内蒙古」）
const CITY_SORTED = CITY_BASE.slice().sort((a, b) => b.length - a.length);

function normStr(s) {
  return String(s == null ? '' : s).trim().replace(/\s+/g, '');
}
function fixProvince(p) {
  if (!p) return '';
  if (PROVINCE_MAP[p]) return PROVINCE_MAP[p];
  if (p.endsWith('省') || p.endsWith('自治区') || p.endsWith('特别行政区')) return p;
  return p; // 未收录且不带省/区后缀 → 原样（防误伤）
}
function fixCity(c) {
  if (!c) return '';
  for (const s of CITY_SUFFIX) if (c.endsWith(s)) return c;
  return c + '市';
}
function fixDistrict(d) {
  if (!d) return '';
  for (const s of DISTRICT_SUFFIX) if (d.endsWith(s)) return d;
  return d + '区';
}

// 处理「北京市朝阳区」「浙江省杭州市西湖区」「浙江杭州西湖」这类合并/连写写法：
// 仅当省列有值、市/区列为空时触发拆分。
function splitCombined(pRaw, cRaw, dRaw) {
  let p = normStr(pRaw);
  let c = normStr(cRaw);
  let d = normStr(dRaw);
  if (p && !c && !d) {
    // 1) 按最长省/直辖市前缀匹配
    const keys = Object.keys(PROVINCE_MAP).sort((a, b) => b.length - a.length);
    const mk = keys.find((k) => p.startsWith(k));
    if (mk) {
      const rest = p.slice(mk.length);
      p = PROVINCE_MAP[mk];
      if (rest) {
        if (MUNICIPALITIES.includes(p)) {
          // 直辖市：省=市，剩余全部归区
          c = p;
          d = rest;
        } else {
          // 2) 优先按「市」后缀切分（最常见，且避免把「杭州市」误在「州」处提前切断）
          const m = rest.match(/^(.+市)(.*)$/);
          let cityMatched = false;
          if (m && m[1]) { c = m[1]; d = m[2]; cityMatched = true; }
          // 3) 无「市」后缀（如「苏州」「温州」连写）→ 用语名词典匹配最长市名前缀，并补「市」
          if (!cityMatched) {
            const city = CITY_SORTED.find((n) => rest.startsWith(n));
            if (city) { c = city + '市'; d = rest.slice(city.length); cityMatched = true; }
          }
          // 4) 启发式兜底：短串当作市；无法识别则整段归区/县（不强行猜）
          if (!cityMatched) {
            if (rest.length <= 3) { c = rest; d = ''; }
            else { d = rest; c = ''; }
          }
        }
      }
    }
  }
  return { p, c, d };
}

// 主入口：返回标准化后的 { province, city, district }
function normalizeRegion(pRaw, cRaw, dRaw) {
  const { p, c, d } = splitCombined(pRaw, cRaw, dRaw);
  const prov = fixProvince(p);
  return {
    province: prov,
    city: MUNICIPALITIES.includes(prov) ? prov : fixCity(c),
    district: fixDistrict(d),
  };
}

